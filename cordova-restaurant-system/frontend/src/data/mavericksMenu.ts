function drinkItem(
  id: string,
  categoryId: string,
  categoryName: string,
  name: string,
  price: number,
  imageName: string,
  description = '',
): MenuItem {
  return {
    id: `mi-mavericks-${id}`,
    restaurant_id: 'mavericks-by-the-baker-street',
    category_id: categoryId,
    category_name: categoryName,
    name,
    description,
    price,
    image_url: `/images/mavericks/${imageName}.jpg`,
    is_available: true,
    dietary_tags: [],
  };
}

